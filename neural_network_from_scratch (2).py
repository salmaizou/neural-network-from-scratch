class MLP:
    def __init__(self, couches):
        self.couches = couches

    def propager(self, entrees):
        for couche_actuelle in self.couches:
            entrees = couche_actuelle.propager(entrees)
        return entrees

    def parameters(self):
        params = []
        for couche_actuelle in self.couches:
            params.extend(couche_actuelle.parameters())
        return params

