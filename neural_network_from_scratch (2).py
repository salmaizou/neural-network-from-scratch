import math

class Nombre:

    def __init__(self, h_val, _parent=(), _op=''):
        self.h_val = h_val
        self.b_val = 0.0
        self._derive = lambda: None
        self._parent = set(_parent)
        self._op = _op



    def __repr__(self):
        return f"[h_val: {self.h_val}, b_val: {self.b_val}]"



    def __add__(self, autre):
        autre = autre if isinstance(autre, Nombre) else Nombre(h_val=autre)
        somme = Nombre(h_val=self.h_val + autre.h_val, _parent=(self, autre), _op='+')

        def _derive():
            self.b_val += somme.b_val
            autre.b_val += somme.b_val

        somme._derive = _derive
        return somme




    def __mul__(self, autre):
        autre = autre if isinstance(autre, Nombre) else Nombre(h_val=autre)
        produit = Nombre(h_val=self.h_val * autre.h_val, _parent=(self, autre), _op='*')

        def _derive():
            self.b_val += autre.h_val * produit.b_val
            autre.b_val += self.h_val * produit.b_val

        produit._derive = _derive
        return produit




    def __pow__(self, autre):
        autre = autre if isinstance(autre, Nombre) else Nombre(h_val=autre)
        puissance = Nombre(h_val=self.h_val ** autre.h_val, _parent=(self, autre), _op='**')

        def _derive():
            self.b_val += autre.h_val * (self.h_val ** (autre.h_val - 1)) * puissance.b_val
            autre.b_val += math.log(self.h_val) * (self.h_val ** autre.h_val) * puissance.b_val

        puissance._derive = _derive
        return puissance



    def __max__(self, autre):
        autre = autre if isinstance(autre, Nombre) else Nombre(h_val=autre)
        max_val = Nombre(h_val=max(self.h_val, autre.h_val), _parent=(self, autre), _op='max')

        def _derive():
            self.b_val += max_val.b_val if self.h_val > autre.h_val else 0.0
            autre.b_val += max_val.b_val if autre.h_val > self.h_val else 0.0

        max_val._derive = _derive
        return max_val


    def __neg__(self):
        return self * -1

    def __sub__(self, autre):
        return self + (-autre)


    def __rmul__(self, autre):
        return self * autre

    def __radd__(self, autre):
        return self + autre

    def tanh(self):
        t = math.tanh(self.h_val)
        out = Nombre(h_val=t, _parent=(self,), _op='tanh')

        def _derive():
            self.b_val += (1 - t**2) * out.b_val

        out._derive = _derive
        return out

    def exp(self):
        out = Nombre(math.exp(self.h_val), _parent=(self,), _op='exp')

        def _derive():
            self.b_val += out.h_val * out.b_val

        out._derive = _derive
        return out

    def _retropropager(self):
        topo = []
        seen = set()

        def construire_graph(nbr):
            if nbr not in seen:
                seen.add(nbr)
                for p in nbr._parent:
                    construire_graph(p)
                topo.append(nbr)

        construire_graph(self)

        self.b_val = 1.0

        for nbr in reversed(topo):
            nbr._derive()

