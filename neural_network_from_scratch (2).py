"""## 1. Neuron"""

class Neuron:
    def __init__(self, poids, biais):
        self.poids = [p if isinstance(p, Nombre) else Nombre(p) for p in poids]
        self.biais = biais if isinstance(biais, Nombre) else Nombre(biais)

    def propager(self, entrees):
        assert len(entrees) == len(self.poids)

        z = self.biais

        for x, w in zip(entrees, self.poids):
            x = x if isinstance(x, Nombre) else Nombre(x)
            z = z + x * w

        return z.tanh()

    def parameters(self):
        return self.poids + [self.biais]

