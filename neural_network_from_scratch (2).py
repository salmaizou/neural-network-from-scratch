"""## 2. Layer"""

class couche:
    def __init__(self, neurons):
        self.neurons = neurons

    def propager(self, caracteres):
        return [neuron.propager(caracteres) for neuron in self.neurons]

    def parameters(self):
        params = []
        for neuron in self.neurons:
            params.extend(neuron.parameters())
        return params

